"""
FEATURE 14: Export. Converts the markdown produced by rag_service into a
styled, downloadable PDF. Kept as its own service so every export route
(summary, compare, literature, presentation, viva) shares one renderer.
"""
import io
from datetime import datetime

import markdown as md
from xhtml2pdf import pisa

_CSS = """
<style>
  @page { size: A4; margin: 2.2cm; }
  body { font-family: Helvetica, Arial, sans-serif; font-size: 10.5pt; color: #101828; line-height: 1.5; }
  h1 { font-size: 18pt; color: #1C817B; margin-bottom: 2pt; }
  h2 { font-size: 13pt; color: #1C817B; margin-top: 16pt; margin-bottom: 6pt; border-bottom: 1px solid #E4E9F0; padding-bottom: 3pt; }
  h3 { font-size: 11.5pt; color: #344054; margin-top: 12pt; margin-bottom: 4pt; }
  p { margin: 4pt 0; }
  ul, ol { margin: 4pt 0 4pt 14pt; padding: 0; }
  li { margin: 2pt 0; }
  table { border-collapse: collapse; width: 100%; margin: 8pt 0; font-size: 9.5pt; }
  th, td { border: 1px solid #E4E9F0; padding: 5pt 7pt; text-align: left; vertical-align: top; }
  th { background-color: #EAF7F6; color: #1C817B; font-weight: bold; }
  .meta { color: #667085; font-size: 9pt; margin-bottom: 14pt; }
  strong { color: #101828; }
</style>
"""


def markdown_to_pdf(title: str, subtitle: str, markdown_content: str) -> bytes:
    """Renders a titled PDF from markdown text. Returns raw PDF bytes."""
    body_html = md.markdown(markdown_content, extensions=["tables", "fenced_code"])

    generated_at = datetime.utcnow().strftime("%B %d, %Y at %H:%M UTC")
    full_html = f"""
    <html>
    <head>{_CSS}</head>
    <body>
      <h1>{title}</h1>
      <p class="meta">{subtitle} &middot; Generated by ResearchMind AI on {generated_at}</p>
      {body_html}
    </body>
    </html>
    """

    buffer = io.BytesIO()
    result = pisa.CreatePDF(src=full_html, dest=buffer)
    if result.err:
        raise RuntimeError("Failed to render PDF from markdown content.")
    return buffer.getvalue()
